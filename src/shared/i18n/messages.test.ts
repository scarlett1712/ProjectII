import { readFileSync } from "node:fs";
import path from "node:path";
import { createTranslator } from "next-intl";
import { describe, expect, it } from "vitest";
import { DEFAULT_LOCALE, LOCALES } from "./locales";
import { messagesByLocale } from "./messages";

type Tree = { [key: string]: string | string[] | Tree };

function leaves(tree: Tree, prefix = ""): [string, string | string[]][] {
  return Object.entries(tree).flatMap(([key, value]) => {
    const fullKey = prefix ? `${prefix}.${key}` : key;
    return typeof value === "object" && !Array.isArray(value) ? leaves(value, fullKey) : [[fullKey, value]];
  });
}

const base = messagesByLocale[DEFAULT_LOCALE] as unknown as Tree;
const root = path.resolve(__dirname, "../../..");

describe("messages", () => {
  it.each(LOCALES)("%s has exactly the keys of the default locale", (locale) => {
    const keys = leaves(messagesByLocale[locale] as unknown as Tree).map(([key]) => key);
    expect(keys.sort()).toEqual(leaves(base).map(([key]) => key).sort());
  });

  it.each(LOCALES)("%s: every text is non-empty NFC", (locale) => {
    for (const [key, value] of leaves(messagesByLocale[locale] as unknown as Tree)) {
      for (const text of [value].flat()) {
        expect(text.trim(), key).not.toBe("");
        expect(text.normalize("NFC"), key).toBe(text);
      }
    }
  });

  it.each(LOCALES)("%s: every ICU message formats without errors", (locale) => {
    const errors: string[] = [];
    const t = createTranslator({
      locale,
      messages: messagesByLocale[locale],
      onError: (error) => errors.push(error.message),
    });
    for (const [key, value] of leaves(messagesByLocale[locale] as unknown as Tree)) {
      if (Array.isArray(value)) continue;
      const args = Object.fromEntries([...value.matchAll(/\{(\w+)/g)].map(([, name]) => [name, "x"]));
      (t as unknown as (key: string, values: object) => string)(key, args);
    }
    expect(errors).toEqual([]);
  });

  it("vi.d.json.ts matches vi.json (regenerated by next dev/build)", () => {
    const json = readFileSync(path.join(root, "messages/vi.json"), "utf8");
    const declaration = readFileSync(path.join(root, "messages/vi.d.json.ts"), "utf8");
    expect(declaration).toContain(`declare const messages: ${json.trim()};`);
  });
});
